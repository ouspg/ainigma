import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import path from "node:path";
import yaml from "js-yaml";

const root = fileURLToPath(new URL("../../../courses", import.meta.url));
const output = fileURLToPath(
  new URL("../src/lib/learning/course-manifest.generated.ts", import.meta.url),
);

function filesIn(directory) {
  return readdirSync(directory, { withFileTypes: true }).flatMap((entry) => {
    const fullPath = path.join(directory, entry.name);
    return entry.isDirectory()
      ? filesIn(fullPath)
      : /\.(md|mdx)$/.test(entry.name)
        ? [fullPath]
        : [];
  });
}

function frontmatter(file) {
  const source = readFileSync(file, "utf8");
  const match = source.match(/^---\s*\n([\s\S]*?)\n---(?:\s|$)/);
  if (!match) throw new Error(`Missing frontmatter: ${path.relative(root, file)}`);
  const data = yaml.load(match[1], { schema: yaml.JSON_SCHEMA });
  if (!data || typeof data !== "object" || Array.isArray(data)) {
    throw new Error(`Invalid frontmatter: ${path.relative(root, file)}`);
  }
  return data;
}

const records = filesIn(root).map((file) => ({
  id: path
    .relative(root, file)
    .replace(/\.(md|mdx)$/, "")
    .replace(/\/index$/, ""),
  data: frontmatter(file),
}));
for (const record of records) {
  if (!["course", "week", "task", "course-page"].includes(record.data.kind)) {
    throw new Error(`Unknown course record kind in ${record.id}: ${record.data.kind}`);
  }
}
const courses = records.filter(({ data }) => data.kind === "course");
if (courses.length === 0) throw new Error("No course overview files found");
const definitions = courses.map(({ id: slug, data: overview }) => {
  for (const field of [
    "definitionKey",
    "code",
    "navMark",
    "startDate",
    "endDate",
    "title",
    "summary",
    "tone",
  ]) {
    if (typeof overview[field] !== "string" || overview[field].length === 0) {
      throw new Error(`Missing course field ${field} in ${slug}`);
    }
  }
  const entries = records.filter(
    (record) => record.id === slug || record.id.startsWith(`${slug}/`),
  );
  const weeks = entries
    .filter(({ data }) => data.kind === "week")
    .sort((a, b) => a.data.order - b.data.order)
    .map(({ id, data }) => ({
      slug: id.slice(`${slug}/`.length),
      number: data.weekNumber,
      title: data.title,
      summary: data.summary,
      tasks: entries
        .filter(({ id: taskId, data: task }) => task.kind === "task" && taskId.startsWith(`${id}/`))
        .sort((a, b) => a.data.order - b.data.order)
        .map(({ id: taskId, data: task }) => ({
          slug: taskId.slice(`${id}/`.length),
          title: task.navLabel ?? task.title,
          summary: task.summary,
          estimatedMinutes: task.estimatedMinutes,
          points: task.points,
        })),
    }));
  const pages = entries
    .filter(({ data }) => data.kind === "course-page")
    .sort((a, b) => a.data.order - b.data.order)
    .map(({ data }) => ({
      page: data.page,
      title: data.title,
      label: data.navLabel ?? data.title,
    }));
  return {
    slug,
    definitionKey: overview.definitionKey,
    code: overview.code,
    navMark: overview.navMark,
    startDate: overview.startDate,
    endDate: overview.endDate,
    title: overview.title,
    summary: overview.summary,
    catalogUrl: overview.catalogUrl ?? null,
    catalogOrder: overview.catalogOrder ?? 0,
    tone: overview.tone,
    draft: overview.draft ?? false,
    weeks,
    pages,
    taskCount: weeks.reduce((count, week) => count + week.tasks.length, 0),
  };
});

const duplicate = new Set();
for (const definition of definitions) {
  if (
    duplicate.has(definition.slug) ||
    definitions.some(
      (other) => other !== definition && other.definitionKey === definition.definitionKey,
    )
  ) {
    throw new Error(`Duplicate course slug or definition key: ${definition.slug}`);
  }
  duplicate.add(definition.slug);
}

const source = `// @generated by scripts/build-course-manifest.mjs — do not edit manually.\nimport type { CourseDefinition } from "./types";\n\nexport const COURSE_DEFINITIONS = ${JSON.stringify(definitions, null, 2)} as const satisfies readonly CourseDefinition[];\n`;
writeFileSync(output, source);
console.log(`wrote ${output} (${source.length} bytes)`);
