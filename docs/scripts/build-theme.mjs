import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { docsTheme } from "../config/theme.mjs";

function kebabCase(value) {
  return value.replace(/[A-Z]/g, (character) => `-${character.toLowerCase()}`);
}

function fontStack({ family, fallbacks }) {
  const quotedFamily = family.includes(" ") ? `"${family}"` : family;
  return `${quotedFamily}, ${fallbacks}`;
}

function renderVariables(mode) {
  const colorIndex = mode === "light" ? 0 : 1;
  const colors = Object.entries(docsTheme.colors).map(
    ([name, values]) => `  --ainigma-color-${kebabCase(name)}: ${values[colorIndex]};`,
  );

  return colors.join("\n");
}

const css = `/* @generated by scripts/build-theme.mjs (${docsTheme.name}) — do not edit manually. */
:root {
  --ainigma-font-body: ${fontStack(docsTheme.typography.body)};
  --ainigma-font-heading: ${fontStack(docsTheme.typography.heading)};
  --ainigma-font-code: ${fontStack(docsTheme.typography.code)};
  --ainigma-radius-inner: ${docsTheme.radii.inner};
  --ainigma-radius-element: ${docsTheme.radii.element};
  --ainigma-radius-container: ${docsTheme.radii.container};
  --ainigma-radius-page: ${docsTheme.radii.page};
  --ainigma-shadow-low: ${docsTheme.shadows.low};
  --ainigma-shadow-medium: ${docsTheme.shadows.medium};
${renderVariables("light")}
}

:root[data-mode="dark"] {
${renderVariables("dark")}
}
`;

const outputPath = fileURLToPath(new URL("../src/styles/theme.generated.css", import.meta.url));
writeFileSync(outputPath, css);
console.log(`wrote ${outputPath} (${css.length} bytes)`);
